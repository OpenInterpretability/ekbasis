"""Builds confirm_wild.py (SPEC.md, the confirmation set) from git_wild.py: another project (file names, contents,
branch names, ignored paths, worktree/submodule/tag names), a new seed prefix, one instance per variant (two for the
templates of the hidden-state families), plus the new command types the SPEC lists. Every replacement is asserted, so a
change in git_wild.py cannot slip through silently. python3 make_confirm_wild.py <git_wild.py> <confirm_wild.py>"""
import sys

src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()


def rep(a, b, count=None):
    global s
    n = s.count(a)
    assert n and (count is None or n == count), (a, n)
    s = s.replace(a, b)


