"""P8: a stand-in for the rig-only /dev/shm/conseq/short_eval.json that short_eval_release.py reads. It held (a) the item
list, which short_eval_release.py only asserts equal to the one it generates itself, and (b) Qwen3.8-27B's answers,
used for the Qwen rows and the routing rule. Rebuilt here:
- items: generated exactly as short_eval_release.py / short_eval.py generate them (robust_eval.items, seed 77); the
  original wordings equal the hand-off of the same items to Claude, 120 of 120 (common/identity_offline.py);
- Qwen3.8-27B reasoning ("think"): right on every item. Published: 100.0% on both wordings, 120 items each
  (short_eval_release.json, accuracy), so each of the 240 answers was right; its token count per item is set to the
  published mean (197.30416666666667), so the mean the script prints is the published one;
- Qwen3.8-27B answering at once ("nothink"): its per-item answers are not recoverable (published only as 80.8% / 80.8%);
  the ported script leaves that row out (CHANGES.diff) and compare.py quotes the published values.
The routing rule then is exactly the release's: an item sent to the reasoning model counts as right.
Writes the stand-in and, next to it, deviation.json (the deviation as approved by the main thread on 2026-10-15), so
the P8 output folder states it; compare.py repeats it.
  python3 make_saved.py <out.json>"""
import json
import os
import random
import sys

DEVIATION = (
    "P8 deviation (documented, approved 2026-10-15): the release read Qwen3.8-27B's answers from "
    "/dev/shm/conseq/short_eval.json, which existed only on the old rig and is gone. It was replaced by a rebuilt "
    "stand-in (P8/make_saved.py): the same 240 items, regenerated by the same code with the same seed (the original "
    "wordings equal the Claude hand-off, 120 of 120); Qwen3.8-27B reasoning right on every item, as published (100% on "
    "both wordings), so the routing rule is exact; the 'Qwen3.8-27B at once' row is dropped because its per-item "
    "answers are gone (published: 80.8% / 80.8%).")


def main():
    out = sys.argv[1]
    sys.argv = sys.argv[:1]
    sys.path.insert(0, os.environ.get("LIB", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib")))
    import robust_eval as R
    from worldgen import Jugs, Machines, Toggles

    R.BIG = False
    rng = random.Random(77)
    items = [(fam, gold, name) for F in (Machines, Toggles, Jugs) for fam, gold, v in R.items(F, rng, 40)
             for name, (text, q) in v.items() if name in ("orig", "para")]
    assert len(items) == 240
    json.dump({"items": items, "res": {"think": [{"ok": True, "tok": 197.30416666666667}] * len(items), "nothink": []},
               "deviation": DEVIATION}, open(out, "w"))
    json.dump({"item": "P8", "deviation": DEVIATION}, open(os.path.join(os.path.dirname(os.path.abspath(out)), "deviation.json"), "w"), indent=1)
    print("wrote", out, len(items), "items")
    print(DEVIATION)


if __name__ == "__main__":
    main()
